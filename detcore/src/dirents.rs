#[cfg(test)]
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
pub struct Dirent64<'a> {
    pub(crate) ino: u64,
    pub(crate) off: i64,
    pub(crate) ty: u8,
    pub(crate) reclen: u16,
    /// null terminated c string, NB: multiple null bytes are expected!
    /// We do not use the std::ffi::CStr because it enforces a check that
    /// there are no interior null bytes, while Linux's own implementation
    /// seems to provide multiple null bytes
    pub(crate) name: &'a [u8],
}

// sort by name, but "." < ".." <= ..
#[cfg(test)]
#[allow(clippy::non_canonical_partial_ord_impl)]
impl<'a> PartialOrd for Dirent64<'a> {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        if self.name == b".\0" {
            Some(Ordering::Less)
        } else if other.name == b".\0" {
            Some(Ordering::Greater)
        } else if self.name == b"..\0" {
            Some(Ordering::Less)
        } else if other.name == b"..\0" {
            Some(Ordering::Greater)
        } else {
            self.name.partial_cmp(other.name)
        }
    }
}

#[cfg(test)]
impl<'a> Ord for Dirent64<'a> {
    fn cmp(&self, other: &Self) -> Ordering {
        self.partial_cmp(other).unwrap()
    }
}

#[cfg(test)]
pub unsafe fn deserialize_dirents64(bytes: &[u8]) -> Vec<Dirent64<'_>> {
    unsafe {
        let mut res = Vec::new();

        let dirp: *const u8 = bytes.as_ptr();
        let nb = bytes.len();
        let mut k = 0;

        while k < nb as isize {
            let dirp = dirp.offset(k);
            let mut j: isize = 0;
            let ino = ptr::read(dirp.offset(j).cast::<u64>());
            j += std::mem::size_of::<u64>() as isize;
            let off = ptr::read(dirp.offset(j).cast::<i64>());
            j += std::mem::size_of::<i64>() as isize;
            let reclen = ptr::read(dirp.offset(j).cast::<u16>());
            j += std::mem::size_of::<u16>() as isize;
            let ty = ptr::read(dirp.offset(j).cast::<u8>());
            j += std::mem::size_of::<u8>() as isize;
            let name = std::slice::from_raw_parts(dirp.offset(j), 1 + reclen as usize - j as usize);
            let ent = Dirent64 {
                ino,
                off,
                reclen,
                ty,
                name,
            };
            res.push(ent);
            k += reclen as isize;
        }
        res
    }
}

#[cfg(test)]
pub unsafe fn serialize_dirents64(dents: &[Dirent64], bytes: &mut [u8]) -> usize {
    unsafe {
        let nb = bytes.len();
        let mut k = 0;
        let mut i = 0;

        while k < nb as isize && i < dents.len() {
            let ent = &dents[i];
            let dirp = bytes.as_mut_ptr().offset(k);
            let mut j: isize = 0;
            ptr::write(dirp.offset(j).cast::<u64>(), ent.ino);
            j += std::mem::size_of::<u64>() as isize;
            ptr::write(dirp.offset(j).cast::<i64>(), ent.off);
            j += std::mem::size_of::<i64>() as isize;
            ptr::write(dirp.offset(j).cast::<u16>(), ent.reclen);
            j += std::mem::size_of::<u16>() as isize;
            ptr::write(dirp.offset(j).cast::<u8>(), ent.ty);
            j += std::mem::size_of::<u8>() as isize;
            let reclen = ent.reclen;
            ptr::copy_nonoverlapping(
                ent.name.as_ptr(),
                dirp.offset(j),
                // NOTE: name is null-terminated with the man page
                // explicitly warning against other methods to read
                // d_name besides strlen(): https://man7.org/linux/man-pages/man3/readdir.3.html
                strlen(ent.name.as_ptr() as *const libc::c_char),
            );
            k += reclen as isize;
            i += 1;
        }
        dents.len()
    }
}

