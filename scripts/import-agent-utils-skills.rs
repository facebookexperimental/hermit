//! Regenerate the skills imported from agent-utils (`lib/agent_utils_skills.rs`).
//!
//! Usage, from the repository root:
//!
//!   scripts/import-agent-utils-skills.rs AGENT_UTILS_CHECKOUT [COMMIT]
//!
//! COMMIT defaults to the checkout's `origin/main`, so fetch it first. For every
//! imported skill this rewrites `.claude/skills/<name>/SKILL.md` from the
//! upstream file at COMMIT, adds the `.agents/skills/<name>` link when missing,
//! records COMMIT and each upstream file's SHA-256 in
//! `scripts/agent-utils-skills.lock`, and then runs the check that
//! `scripts/check-skill-discovery.rs` runs, against the same checkout.

#[path = "lib/agent_utils_skills.rs"]
mod agent_utils_skills;
#[path = "lib/rust_script_prelude.rs"]
mod rust_script_prelude;

use std::env;
use std::fs;
use std::os::unix::fs::symlink;
use std::path::Path;
use std::path::PathBuf;
use std::process::Command;

use agent_utils_skills::IMPORTED;
use agent_utils_skills::LOCK;

const USAGE: &str = "usage: scripts/import-agent-utils-skills.rs AGENT_UTILS_CHECKOUT [COMMIT]";

fn resolve_commit(checkout: &Path, revision: &str) -> Result<String, String> {
    let output = Command::new("git")
        .arg("-C")
        .arg(checkout)
        .args(["rev-parse", "--verify", &format!("{revision}^{{commit}}")])
        .output()
        .map_err(|error| format!("cannot run git: {error}"))?;
    let commit = String::from_utf8_lossy(&output.stdout).trim().to_owned();
    if !output.status.success() || commit.len() != 40 {
        return Err(format!(
            "{} has no commit {revision}",
            checkout.display()
        ));
    }
    Ok(commit)
}

fn run() -> Result<String, String> {
    let args: Vec<String> = env::args().skip(1).collect();
    let (checkout, revision) = match args.as_slice() {
        [checkout] => (PathBuf::from(checkout), "origin/main"),
        [checkout, revision] => (PathBuf::from(checkout), revision.as_str()),
        _ => return Err(USAGE.to_owned()),
    };
    let root = Path::new(".");
    if !root.join(".claude/skills").is_dir() || !root.join("scripts").is_dir() {
        return Err(format!("run from the repository root; {USAGE}"));
    }
    agent_utils_skills::regression_test()?;
    let commit = resolve_commit(&checkout, revision)?;

    let mut lock = format!(
        "# Skills imported from agent-utils (https://github.com/rrnewton/agent-utils),\n\
         # the source of truth. Generated by scripts/import-agent-utils-skills.rs; do\n\
         # not edit. Each skill line is the SHA-256 of the upstream SKILL.md.\n\
         commit {commit}\n"
    );
    for name in IMPORTED {
        let entries = agent_utils_skills::upstream_entries(&checkout, &commit, name)?;
        if entries != [format!("skills/{name}/SKILL.md")] {
            return Err(format!(
                "agent-utils {commit} skills/{name}/ holds {entries:?}; only a lone SKILL.md \
                 is imported"
            ));
        }
        let upstream = agent_utils_skills::upstream_file(&checkout, &commit, name)?;
        let dir = root.join(".claude/skills").join(name);
        fs::create_dir_all(&dir)
            .map_err(|error| format!("cannot create {}: {error}", dir.display()))?;
        let path = dir.join("SKILL.md");
        fs::write(&path, agent_utils_skills::render(&upstream, &commit, name)?)
            .map_err(|error| format!("cannot write {}: {error}", path.display()))?;
        let link = root.join(".agents/skills").join(name);
        if fs::symlink_metadata(&link).is_err() {
            symlink(format!("../../.claude/skills/{name}"), &link)
                .map_err(|error| format!("cannot link {}: {error}", link.display()))?;
        }
        let hash = agent_utils_skills::sha256(upstream.as_bytes())?;
        lock.push_str(&format!("skill {name} {hash}\n"));
    }
    fs::write(root.join(LOCK), lock).map_err(|error| format!("cannot write {LOCK}: {error}"))?;
    agent_utils_skills::check(root, Some(&checkout))
}

fn main() {
    rust_script_prelude::init();
    match run() {
        Ok(summary) => println!("import-agent-utils-skills: {summary}"),
        Err(error) => {
            eprintln!("import-agent-utils-skills: ERROR: {error}");
            std::process::exit(1);
        }
    }
}
